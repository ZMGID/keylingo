fn close_objects(value: &mut Value) {
    match value {
        Value::Object(object) => {
            if object.contains_key("properties")
                || object.get("type").and_then(Value::as_str) == Some("object")
            {
                object.insert("additionalProperties".to_string(), Value::Bool(false));
            }
            for child in object.values_mut() {
                close_objects(child);
            }
        }
        Value::Array(items) => {
            for item in items {
                close_objects(item);
            }
        }
        _ => {}
    }
}

fn constrain_protocol_versions(value: &mut Value) {
    match value {
        Value::Object(object) => {
            if let Some(properties) = object.get_mut("properties").and_then(Value::as_object_mut) {
                if properties.contains_key("protocolVersion") {
                    properties.insert(
                        "protocolVersion".to_string(),
                        serde_json::json!({ "type": "integer", "const": CHAT_PROTOCOL_VERSION }),
                    );
                }
            }
            for child in object.values_mut() {
                constrain_protocol_versions(child);
            }
        }
        Value::Array(items) => {
            for item in items {
                constrain_protocol_versions(item);
            }
        }
        _ => {}
    }
}

fn merge_flattened_envelope(schema: &mut Value, scope: &str) {
    let Some(object) = schema.as_object_mut() else {
        return;
    };
    let Some(mut common) = object
        .remove("properties")
        .and_then(|value| value.as_object().cloned())
    else {
        return;
    };
    common.insert(
        "protocolVersion".to_string(),
        serde_json::json!({ "type": "integer", "const": CHAT_PROTOCOL_VERSION }),
    );
    common.insert(
        "scope".to_string(),
        serde_json::json!({ "type": "string", "const": scope }),
    );
    let common_required = object
        .remove("required")
        .and_then(|value| value.as_array().cloned())
        .unwrap_or_default();
    if let Some(variants) = object.get_mut("oneOf").and_then(Value::as_array_mut) {
        for variant in variants {
            let Some(variant) = variant.as_object_mut() else {
                continue;
            };
            let properties = variant
                .entry("properties")
                .or_insert_with(|| Value::Object(Default::default()));
            if let Some(properties) = properties.as_object_mut() {
                for (name, value) in &common {
                    properties.insert(name.clone(), value.clone());
                }
            }
            let required = variant
                .entry("required")
                .or_insert_with(|| Value::Array(Vec::new()));
            if let Some(required) = required.as_array_mut() {
                for name in &common_required {
                    if !required.contains(name) {
                        required.push(name.clone());
                    }
                }
            }
        }
    }
    object.remove("type");
    object.remove("unevaluatedProperties");
    object.remove("additionalProperties");
}

fn schema() -> String {
    let mut schema = serde_json::to_value(schema_for!(ChatProtocolEvent))
        .expect("chat protocol schema must serialize");
    if let Some(definitions) = schema.get_mut("$defs").and_then(Value::as_object_mut) {
        if let Some(run) = definitions.get_mut("ChatRunEventEnvelope") {
            merge_flattened_envelope(run, "run");
        }
        if let Some(conversation) = definitions.get_mut("ChatConversationEventEnvelope") {
            merge_flattened_envelope(conversation, "conversation");
        }
    }
    close_objects(&mut schema);
    constrain_protocol_versions(&mut schema);
    format!(
        "{}\n",
        serde_json::to_string_pretty(&schema).expect("chat protocol schema must encode")
    )
}

fn sync_schema() -> String {
    let mut schema =
        serde_json::to_value(schema_for!(ChatSyncResult)).expect("chat sync schema must serialize");
    if let Some(definitions) = schema.get_mut("$defs").and_then(Value::as_object_mut) {
        if let Some(run) = definitions.get_mut("ChatRunEventEnvelope") {
            merge_flattened_envelope(run, "run");
        }
    }
    close_objects(&mut schema);
    constrain_protocol_versions(&mut schema);
    format!(
        "{}\n",
        serde_json::to_string_pretty(&schema).expect("chat sync schema must encode")
    )
}

fn write_or_check(path: &Path, expected: &str, check: bool) -> Result<(), String> {
    if check {
        let actual = fs::read_to_string(path).map_err(|_| {
            format!(
                "{} is missing; run npm run protocol:generate",
                path.display()
            )
        })?;
        if actual != expected {
            return Err(format!(
                "{} is stale; run npm run protocol:generate",
                path.display()
            ));
        }
        return Ok(());
    }
    fs::write(path, expected).map_err(|error| format!("write {}: {error}", path.display()))
}

fn verify_strict_deserialization() {
    let valid = serde_json::json!({
        "protocolVersion": CHAT_PROTOCOL_VERSION,
        "scope": "run",
        "conversationId": "conversation",
        "runId": "run",
        "messageId": "message",
        "seq": 1,
        "baseRevision": 0,
        "type": "run_started",
        "recovery": null
    });
    serde_json::from_value::<ChatProtocolEvent>(valid.clone())
        .expect("generated run event must deserialize");
    let mut invalid = valid;
    invalid
        .as_object_mut()
        .expect("wire sample is an object")
        .insert("unexpected".to_string(), Value::Bool(true));
    assert!(
        serde_json::from_value::<ChatProtocolEvent>(invalid).is_err(),
        "protocol objects must reject additional fields"
    );
}

fn main() {
    verify_strict_deserialization();
    let check = std::env::args().any(|argument| argument == "--check");
    let directory = generated_dir();
    if !check {
        fs::create_dir_all(&directory).expect("create generated protocol directory");
    }
    let results = [
        write_or_check(&directory.join("chatProtocol.ts"), &typescript(), check),
        write_or_check(
            &directory.join("chatProtocol.schema.json"),
            &schema(),
            check,
        ),
        write_or_check(
            &directory.join("chatSync.schema.json"),
            &sync_schema(),
            check,
        ),
    ];
    for result in results {
        if let Err(error) = result {
            eprintln!("{error}");
            std::process::exit(1);
        }
    }
}
